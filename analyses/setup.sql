USE ROLE ACCOUNTADMIN;

-- =====================================================
-- DEV
-- =====================================================
CREATE WAREHOUSE IF NOT EXISTS DBT_DEV_WH
    WAREHOUSE_SIZE = 'XSMALL';

CREATE DATABASE IF NOT EXISTS DBT_DEV_DB;

CREATE ROLE IF NOT EXISTS DBT_DEV_ROLE;

GRANT USAGE ON WAREHOUSE DBT_DEV_WH TO ROLE DBT_DEV_ROLE;
GRANT ALL ON DATABASE DBT_DEV_DB TO ROLE DBT_DEV_ROLE;

CREATE SCHEMA IF NOT EXISTS DBT_DEV_DB.DBT_SCHEMA;

