-- USER ACCESS
-- =====================================================
GRANT ROLE DBT_DEV_ROLE TO USER LXLOGICINC;
GRANT ROLE DBT_UAT_ROLE TO USER LXLOGICINC;
GRANT ROLE DBT_PRD_ROLE TO USER LXLOGICINC;